// Writes docs/commands.md, the command reference, from the command list in src/cli.ts that `fleet help` prints.
// Usage: node scripts/docs-commands.ts [<repo root>]
// Run `npm run site:docs` after it to turn the page into site/docs/commands/index.html. GitHub shows the
// Markdown too, so it is committed; a test fails when it is stale.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { commands, GLOBAL_OPTIONS } from "../src/cli.ts";
import type { Command, CommandOption } from "../src/cli.ts";

/** The guide that covers a command, where there is one: the link's text and its target in docs/. */
export const GUIDES: Record<string, { text: string; target: string }> = {
  doctor: { text: "Logging in to MCP servers", target: "mcp-logins.md" },
  context: { text: "The bridge: startup context", target: "bridge.md#startup-context" },
  bridge: { text: "The bridge", target: "bridge.md" },
  ui: { text: "The page", target: "ui.md" },
  capture: { text: "Capture", target: "capture.md" },
  push: { text: "Getting started: working with fleet", target: "getting-started.md#working-with-fleet" },
  secrets: { text: "FAQ: where do my secrets end up?", target: "faq.md#where-do-my-secrets-end-up" },
  host: { text: "Retiring a machine", target: "setting-up-machines.md#retiring-a-machine" },
  skills: { text: "Getting started: reading a skill update before it moves", target: "getting-started.md#reading-a-skill-update-before-it-moves" },
  update: { text: "FAQ: how do I update fleet?", target: "faq.md#how-do-i-update-fleet" },
  new: { text: "Getting started", target: "getting-started.md" },
  init: { text: "Setting up machines", target: "setting-up-machines.md" },
  demo: { text: "The bridge: trying it on made-up hosts", target: "bridge.md#trying-it-on-made-up-hosts" },
};

const sentence = (s: string) => {
  const t = s.charAt(0).toUpperCase() + s.slice(1);
  return /[.!?]$/.test(t) ? t : `${t}.`;
};
const option = ({ flag, summary }: CommandOption) => `- \`${flag}\`: ${sentence(summary)}`;

function section(c: Command): string {
  const effect = c.effect === "read" ? "**Reads only.** It changes nothing." : "**Changes things.** It writes to this host, to the config repo or to other hosts.";
  const guide = GUIDES[c.name];
  return [
    `## \`fleet ${c.name}\``,
    `${effect}`,
    sentence(c.summary),
    `\`\`\`text\nfleet ${c.usage}\n\`\`\``,
    ...(c.options === undefined || c.options.length === 0 ? [] : ["**Options**", c.options.map(option).join("\n")]),
    c.json === null ? "**JSON.** `--json` is not available for this command." : `**JSON.** ${c.json}`,
    ...(guide === undefined ? [] : [`**Guide.** [${guide.text}](${guide.target})`]),
  ].join("\n\n");
}

/** The whole page. The list is a parameter so a test can feed it a small one. */
export function commandsMarkdown(list: Command[] = commands, globals: CommandOption[] = GLOBAL_OPTIONS): string {
  return `# Commands

<!-- Generated by \`npm run docs:commands\` from the command list in src/cli.ts. Do not edit by hand: change the list and run it again. -->

Every \`fleet\` command and option, as \`fleet help\` lists them. Commands that read only change nothing. The others write to this host, to the config repo or to other hosts, so run them when you mean to.

Add \`--json\` to a command for one JSON document on stdout. It always has \`ok\`, \`code\`, \`host\` and \`messages\`, and each command adds its own fields, listed under it below.

## Options for every command

${globals.map(option).join("\n")}

${list.map(section).join("\n\n")}
`;
}

if (import.meta.main) {
  const root = process.argv[2] ?? join(import.meta.dirname, "..");
  writeFileSync(join(root, "docs/commands.md"), commandsMarkdown());
}
