import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import assert from "node:assert/strict";
import { commandsMarkdown, GUIDES } from "../scripts/docs-commands.ts";
import { commands, GLOBAL_OPTIONS } from "../src/cli.ts";
import { slug } from "../scripts/site-markdown.ts";
import { makeHome, repoRoot, runFleet } from "./helpers.ts";

const read = (path: string) => readFileSync(join(repoRoot, path), "utf8");

test("docs/commands.md is what the command list generates now", () => {
  assert.ok(commandsMarkdown() === read("docs/commands.md"), "docs/commands.md is out of date with src/cli.ts: run 'npm run docs:commands' then 'npm run site:docs' and commit the result");
  assert.match(read("docs/commands.md"), /Generated by `npm run docs:commands`/);
});

test("every command and option of fleet help is on the page", () => {
  const page = read("docs/commands.md");
  const help = runFleet(repoRoot, ["help"], { home: makeHome("laptop") }).stdout;
  const named = [...help.matchAll(/^ {2}([a-z]+) {2}/gm)].map((m) => m[1]);
  assert.deepEqual(named, commands.map((c) => c.name), "fleet help lists the commands in the list");
  for (const c of commands) {
    assert.ok(page.includes(`## \`fleet ${c.name}\`\n`), `no section for ${c.name}`);
    assert.ok(page.includes(`fleet ${c.usage}\n`), `no usage line for ${c.name}`);
    for (const o of c.options ?? []) {
      assert.ok(page.includes(`- \`${o.flag}\`: `), `${c.name}: no ${o.flag}`);
      assert.match(help, new RegExp(`^ {2}${o.flag.replace(/[<>|]/g, "\\$&")} +.*'${c.name}'`, "m"), `fleet help does not show ${o.flag} for ${c.name}`);
    }
  }
  for (const o of GLOBAL_OPTIONS) {
    assert.ok(page.includes(`- \`${o.flag}\`: `), `no ${o.flag}`);
    assert.ok(help.includes(`${o.flag} `), `fleet help has no ${o.flag}`);
  }
});

test("each command says what it changes and what --json adds, and every guide link goes to a heading that exists", () => {
  const page = read("docs/commands.md");
  for (const c of commands) {
    const body = page.slice(page.indexOf(`## \`fleet ${c.name}\`\n`)).split("\n## ")[0]!;
    assert.match(body, c.effect === "read" ? /\*\*Reads only\.\*\*/ : /\*\*Changes things\.\*\*/, c.name);
    assert.match(body, /\*\*JSON\.\*\* /, c.name);
    if (c.json === null) assert.match(body, /is not available/, c.name);
  }
  assert.deepEqual(
    commands.filter((c) => c.json === null).map((c) => c.name),
    ["bridge", "ui"],
    "the commands without a --json form",
  );
  for (const [name, { target }] of Object.entries(GUIDES)) {
    assert.ok(commands.some((c) => c.name === name), `GUIDES names ${name}, which is not a command`);
    const [file, anchor] = target.split("#") as [string, string | undefined];
    assert.ok(existsSync(join(repoRoot, "docs", file)), `${target}: no such doc`);
    if (anchor !== undefined) {
      const headings = [...read(`docs/${file}`).matchAll(/^#{1,4} (.+)$/gm)].map((m) => slug(m[1]!));
      assert.ok(headings.includes(anchor), `${target}: no such heading`);
    }
  }
});

test("a command's options are exactly the flags in its usage line", () => {
  for (const c of commands) {
    const inUsage = [...c.usage.matchAll(/(?<![\w-])(--?[a-z][a-z-]*)/g)].map((m) => m[1]);
    const listed = (c.options ?? []).map((o) => o.flag.split(" ")[0]);
    assert.deepEqual([...listed].sort(), [...inUsage].sort(), `${c.name}: options and usage differ`);
  }
});

test("the page has no long dashes", () => {
  assert.doesNotMatch(read("docs/commands.md"), /\u2014/);
});
