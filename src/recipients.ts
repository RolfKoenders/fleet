import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { InvalidConfigError } from "./config.ts";
import { parseFile } from "./yamlfile.ts";

export type Rule = {
  /** `shared` or a host name. */
  file: string;
  /** Age recipients, sorted. */
  recipients: string[];
};

const HOST_NAME = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
const RECIPIENT = /^age1[a-z0-9]+$/;

export const secretsFile = (name: string): string => `secrets/${name}.enc.yaml`;

/** Host names, from the files in `hosts/` other than the defaults. */
export function hostNames(configDir: string): string[] {
  try {
    return readdirSync(join(configDir, "hosts"))
      .filter((f) => f.endsWith(".yaml") && f !== "_defaults.yaml")
      .map((f) => f.slice(0, -".yaml".length))
      .sort();
  } catch {
    return [];
  }
}

/**
 * Who can read each secrets file: `shared` goes to every host with a recipient, `<host>` to that
 * host plus the admin host. A host with an empty `age` is left out.
 */
export function readRules(configDir: string): Rule[] {
  const problems: string[] = [];
  const ages = new Map<string, string>();
  const admins: string[] = [];
  for (const host of hostNames(configDir)) {
    const path = join(configDir, "hosts", `${host}.yaml`);
    if (!HOST_NAME.test(host)) problems.push(`${path}: host name '${host}' must be letters, digits, '.', '_' or '-'`);
    const doc = parseFile(path, false, problems);
    if (doc === null) continue;
    const { age, admin } = doc;
    if (age !== undefined && typeof age !== "string") problems.push(`${path}: 'age' must be a string`);
    else if (typeof age === "string" && age !== "") {
      if (RECIPIENT.test(age)) ages.set(host, age);
      else problems.push(`${path}: 'age' is not an age recipient (it starts with 'age1')`);
    }
    if (admin === true) admins.push(host);
  }
  if (admins.length !== 1) {
    problems.push(`exactly one host file needs 'admin: true', found ${admins.length === 0 ? "none" : admins.join(", ")}`);
  } else if (!ages.has(admins[0]!)) {
    problems.push(`hosts/${admins[0]}.yaml: the admin host needs an 'age' recipient, or no secrets file can be read`);
  }
  if (problems.length > 0) throw new InvalidConfigError(problems);

  const admin = ages.get(admins[0]!)!;
  const sorted = (list: string[]) => [...new Set(list)].sort();
  return [
    { file: "shared", recipients: sorted([...ages.values()]) },
    ...[...ages].map(([host, age]) => ({ file: host, recipients: sorted([age, admin]) })),
  ];
}

const escapeRegex = (text: string) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** The text of `.sops.yaml`. Plain scalars only, built from values checked above. */
export function renderSopsConfig(rules: Rule[]): string {
  const entries = rules.map(
    (rule) => `  - path_regex: '${escapeRegex(secretsFile(rule.file))}$'\n    age: ${rule.recipients.join(",")}\n`,
  );
  return `# Generated by fleet from hosts/*.yaml. Do not edit: run 'fleet secrets rekey'.\ncreation_rules:\n${entries.join("")}`;
}

export function writeSopsConfig(configDir: string): Rule[] {
  const rules = readRules(configDir);
  writeFileSync(join(configDir, ".sops.yaml"), renderSopsConfig(rules));
  return rules;
}
